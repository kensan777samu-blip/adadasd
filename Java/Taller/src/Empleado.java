public class Empleado {
    String cedula;
    double sueldo;
    int edad;
    String genero;
    

    public Empleado(String cedula, double sueldo, int edad, String genero) {
        this.cedula = cedula;
        this.sueldo = sueldo;
        this.edad = edad;
        this.genero = genero;
    }
}
